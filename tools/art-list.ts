/**
 * The Art List (docs/plans/art-pipeline.md sections 3 and 5).
 *
 * Gives every sprite the game uses a permanent code (kept in art/codes.json),
 * then writes art/ART-LIST.md and one contact sheet per group, art/list/<letter>.png,
 * showing every current sprite enlarged with its code.
 *
 * Run with: npm run art:list (after adding sprites to the game, or pressing art).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Manifest } from '../src/render/manifest.ts';
import { assignCodes, compareCodes, GROUPS, madeFrom, readContentNames, type GroupLetter } from './art/groups.ts';
import { blitScaled, checker, drawText, fillRect, flow, loadFont, sheetScale, textWidth } from './art/draw.ts';
import { listSources, loadArt } from './art/press.ts';
import { Image, decodePng, encodePng } from './png.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(readFileSync(join(ROOT, 'assets/manifest.json'), 'utf8')) as Manifest;
const content = readContentNames(ROOT);
const ids = Object.keys(manifest.sprites);
const all = new Set(ids);
const codesPath = join(ROOT, 'art/codes.json');
const before = existsSync(codesPath) ? ((JSON.parse(readFileSync(codesPath, 'utf8')) as { codes: Record<string, string> }).codes ?? {}) : {};
const codes = assignCodes(before, ids, content);
const targetsPath = join(ROOT, 'art/targets.json');
const targets = existsSync(targetsPath) ? (JSON.parse(readFileSync(targetsPath, 'utf8')) as { sizes: Record<string, { size: string }> }).sizes : {};
const ordered = Object.keys(codes).sort(compareCodes);
writeFileSync(
  codesPath,
  JSON.stringify({ note: 'Permanent art codes (owner, 2026-11-23). Never change or reuse a code; npm run art:list adds new ones.', codes: Object.fromEntries(ordered.map((c) => [c, codes[c]])) }, null, 2) + '\n',
);

const sources = listSources(loadArt(ROOT));
const statusOf = (id: string) => {
  const s = sources.find((x) => x.id === id);
  return s ? (s.status === 'approved' ? 'approved' : 'drawn (draft)') : 'placeholder';
};
const human = (id: string) => id.replace(/^(gear|icon|node|upgrade|perm|place|room|town|scenery|trait|rank|tile|face)-/, '').replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase());
const mirrors = new Map<string, string[]>();
for (const id of ids) {
  const from = madeFrom(id, all);
  if (from && !id.includes('@')) mirrors.set(from, [...(mirrors.get(from) ?? []), id]);
}
const themesOf = (id: string) =>
  ids
    .filter((x) => x.startsWith(`${id}@`))
    .map((x) => x.split('@')[1])
    .join(', ');

const counts = Object.fromEntries(Object.keys(GROUPS).map((L) => [L, ordered.filter((c) => c.startsWith(L) && all.has(codes[c]!)).length]));
let md = `# Art List

Every sprite the game uses, with its **permanent code** (owner, 2026-11-23). Write the
code next to your drawing. Codes never change and are never reused.

Made by \`npm run art:list\` from the game's sprite list (\`assets/manifest.json\`), so it
is always up to date. Do not edit this file by hand; edit \`art/codes.json\` only to fix
a mistake, never to renumber.

- **Size** is width × height in game pixels. A size in **bold** is a new size the owner
  chose (\`art/targets.json\`); the placeholder is still the old size. You can draw at any size in the
  sketchbook; Claude renders it down. A sprite may grow if it needs to (Q5).
- **Frames** are the pictures in an animation or the states of an object (open, closed).
- **Made automatically** means no drawing is needed: flipped copies (\`-left\`) and theme
  versions come from your drawing.
- **Contact sheets** (every current sprite enlarged with its code): ${Object.keys(GROUPS)
  .map((L) => `[${L}](list/${L}.png)`)
  .join(' · ')}

| Group | Letter | Sprites |
|---|---|---|
${Object.entries(GROUPS)
  .map(([L, name]) => `| ${name} | ${L} | ${counts[L]} |`)
  .join('\n')}

`;
for (const [L, name] of Object.entries(GROUPS)) {
  md += `## ${L} — ${name}\n\n| Code | Sprite | Name in game | Size | Frames | Made automatically | Status |\n|---|---|---|---|---|---|---|\n`;
  for (const code of ordered.filter((c) => c.startsWith(L))) {
    const id = codes[code]!;
    const e = manifest.sprites[id];
    if (!e) {
      md += `| ${code} | \`${id}\` | (retired: no longer in the game) | | | | |\n`;
      continue;
    }
    const auto = [...(mirrors.get(id) ?? []).map((m) => `\`${m}\` (flipped)`), themesOf(id) ? `themes: ${themesOf(id)}` : ''].filter(Boolean).join('; ');
    const frames = e.frames.length > 8 ? `${e.frames.length} (made from one texture)` : `${e.frames.length}${e.frames.length > 1 ? `: ${e.frames.join(', ')}` : ''}`;
    md += `| **${code}** | \`${id}\` | ${content.names.get(id) ?? human(id)} | ${targets[id] && targets[id].size !== `${e.frameWidth}x${e.frameHeight}` ? `**${targets[id].size.replace('x', '×')}** (now ${e.frameWidth}×${e.frameHeight})` : `${e.frameWidth}×${e.frameHeight}`} | ${frames} | ${auto} | ${statusOf(id)} |\n`;
  }
  md += '\n';
}
writeFileSync(join(ROOT, 'art/ART-LIST.md'), md);

// Contact sheets: every sprite in a group, enlarged, with its code underneath.
const font = loadFont(ROOT, manifest);
const bg: [number, number, number, number] = [40, 40, 54, 255];
const label: [number, number, number, number] = [240, 232, 200, 255];
mkdirSync(join(ROOT, 'art/list'), { recursive: true });
for (const L of Object.keys(GROUPS) as GroupLetter[]) {
  const items = ordered.filter((c) => c.startsWith(L) && manifest.sprites[codes[c]!]).map((code) => {
    const e = manifest.sprites[codes[code]!]!;
    const s = sheetScale(e.frameWidth, e.frameHeight);
    const shown = Math.min(e.frames.length, e.frames.length > 8 ? 1 : 6);
    const w = Math.max(shown * (e.frameWidth * s + 2) - 2, textWidth(font, code, 3));
    return { code, e, s, shown, w, h: e.frameHeight * s + 26 };
  });
  const layout = flow(
    items.map((i) => [i.w, i.h] as const),
    1000,
    14,
  );
  const img = new Image(1000, layout.height);
  fillRect(img, 0, 0, img.width, img.height, bg);
  items.forEach((it, n) => {
    const [x, y] = layout.pos[n]!;
    const pic = decodePng(readFileSync(join(ROOT, 'assets', it.e.file)));
    const cols = Math.max(1, Math.floor(pic.width / it.e.frameWidth));
    for (let f = 0; f < it.shown; f++) {
      const fx = x + f * (it.e.frameWidth * it.s + 2);
      checker(img, fx, y, it.e.frameWidth * it.s, it.e.frameHeight * it.s, Math.max(2, it.s * 2), [58, 58, 74, 255], [50, 50, 64, 255]);
      blitScaled(img, pic, fx, y, it.s, (f % cols) * it.e.frameWidth, Math.floor(f / cols) * it.e.frameHeight, it.e.frameWidth, it.e.frameHeight);
    }
    drawText(img, font, x, y + it.e.frameHeight * it.s + 6, it.code, 3, label);
  });
  writeFileSync(join(ROOT, `art/list/${L}.png`), encodePng(img));
}
console.log(`Art List: ${Object.keys(codes).length} codes (${Object.keys(codes).length - Object.keys(before).length} new). Wrote art/ART-LIST.md and art/list/*.png`);

// Palette swatch (art/STYLE.md): every ramp, dark to light, then each theme's version.
{
  const art = loadArt(ROOT);
  const names = Object.keys(art.ramps);
  const themeNames = ['day', ...Object.keys(art.themes)];
  const sw = 14;
  const colW = 5 * sw + 34;
  const left = 96;
  const img = new Image(left + themeNames.length * colW + 10, 40 + names.length * (sw + 8) + 10);
  fillRect(img, 0, 0, img.width, img.height, bg);
  themeNames.forEach((t, ti) => drawText(img, font, left + ti * colW, 12, t, 2, label));
  names.forEach((n, ri) => {
    const y = 40 + ri * (sw + 8);
    drawText(img, font, 10, y + 2, n, 2, label);
    themeNames.forEach((t, ti) => {
      const ramp = t === 'day' ? art.ramps[n]! : (art.themes[t]![n] ?? art.ramps[n]!);
      ramp.forEach((c, k) => fillRect(img, left + ti * colW + k * sw, y, sw, sw, c));
    });
  });
  writeFileSync(join(ROOT, 'art/list/palette.png'), encodePng(img));
}
